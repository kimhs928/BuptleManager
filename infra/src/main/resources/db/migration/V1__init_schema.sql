-- 운영관리 시스템 DB 초기 스키마 (docs: ERD + 프론트 화면 기준 보완)
-- enum 은 PostgreSQL enum 타입 대신 varchar + CHECK 로 관리한다 (값 추가 시 마이그레이션이 단순하다).

-- 권한
create table management_roles (
    id        bigint generated by default as identity primary key,
    role_code varchar(30) not null,
    role_name varchar(50) not null,
    constraint uk_management_roles_role_code unique (role_code),
    constraint ck_management_roles_role_code check (role_code in ('VIEWER', 'CS', 'DEVELOPER', 'ADMIN'))
);

-- 운영자
create table management_users (
    id            bigint generated by default as identity primary key,
    sso_subject   varchar(255) not null,
    user_email    varchar(255) not null,
    user_name     varchar(100) not null,
    role_id       bigint       not null references management_roles (id),
    is_active     boolean      not null default true,
    last_login_at timestamptz,
    created_at    timestamptz  not null,
    updated_at    timestamptz  not null,
    deleted_at    timestamptz,
    constraint uk_management_users_sso_subject unique (sso_subject),
    constraint uk_management_users_email unique (user_email)
);
create index idx_management_users_role_active on management_users (role_id, is_active);

-- 고객사 (원본은 Biz/Nova 운영 DB, 여기에는 식별·기본 정보 사본)
create table companies (
    id                 bigint generated by default as identity primary key,
    schema_name        varchar(100) not null,
    domain             varchar(255) not null,
    company_name       varchar(200) not null,
    service_platform   varchar(30)  not null,
    ceo_name           varchar(100),
    business_number    varchar(30),
    address            text,
    telephone_number   varchar(30),
    user_limit         integer,
    current_user_count integer,
    is_active          boolean      not null default true,
    source_created_at  timestamptz,
    synced_at          timestamptz,
    created_at         timestamptz  not null,
    updated_at         timestamptz  not null,
    constraint uk_companies_schema_name unique (schema_name),
    constraint uk_companies_domain unique (domain),
    constraint ck_companies_service_platform check (service_platform in ('BUPTLE_BIZ', 'BUPTLE_NOVA'))
);
create index idx_companies_company_name on companies (company_name);
create index idx_companies_is_active on companies (is_active);
create index idx_companies_service_platform on companies (service_platform);

-- 컨피그 정의. 같은 이름이 타입별로 존재할 수 있어 (이름, 타입)을 유일하게 한다.
create table configs (
    id                 bigint generated by default as identity primary key,
    config_name        varchar(255) not null,
    config_scope       varchar(30)  not null,
    default_value      text,
    config_description text,
    created_by         bigint       not null references management_users (id),
    created_at         timestamptz  not null,
    updated_at         timestamptz  not null,
    constraint uk_configs_name_scope unique (config_name, config_scope),
    constraint ck_configs_scope check (config_scope in ('MODULES', 'COMPONENT', 'STANDALONE', 'PUBLIC'))
);
create index idx_configs_scope on configs (config_scope);

-- 고객사에 적용된 컨피그 (PUBLIC 컨피그는 고객사에 속하지 않아 이 테이블을 쓰지 않는다)
create table company_configs (
    company_id   bigint      not null references companies (id),
    config_id    bigint      not null references configs (id),
    config_value text,
    applied_by   bigint      not null references management_users (id),
    applied_at   timestamptz not null,
    updated_at   timestamptz not null,
    primary key (company_id, config_id)
);
create index idx_company_configs_config_company on company_configs (config_id, company_id);

-- 작업 이력
create table operation_logs (
    id                  bigint generated by default as identity primary key,
    operation_key       uuid        not null,
    actor_user_id       bigint      not null references management_users (id),
    operation_category  varchar(30) not null,
    operation_type      varchar(30) not null,
    ticket_number       varchar(100),
    zendesk_ticket_id   varchar(50),
    operation_reason    text,
    request_data        jsonb,
    result_data         jsonb,
    occurred_at         timestamptz not null,
    constraint uk_operation_logs_operation_key unique (operation_key),
    constraint ck_operation_logs_category check (operation_category in
        ('COMPANY', 'CONTRACT', 'COUNSEL', 'LITIGATION', 'USER', 'CONFIG', 'SESSION', 'ERROR_REPORT')),
    constraint ck_operation_logs_type check (operation_type in
        ('SEARCH', 'VIEW', 'UPDATE', 'ADD', 'DELETE', 'TRANSFER', 'EXPORT', 'FORCE_LOGOUT'))
);
create index idx_operation_logs_ticket on operation_logs (ticket_number);
create index idx_operation_logs_actor_occurred on operation_logs (actor_user_id, occurred_at);
create index idx_operation_logs_category_type_occurred on operation_logs (operation_category, operation_type, occurred_at);
create index idx_operation_logs_occurred on operation_logs (occurred_at);

-- 작업이 대상으로 한 고객사
create table operation_companies (
    operation_log_id bigint not null references operation_logs (id),
    company_id       bigint not null references companies (id),
    primary key (operation_log_id, company_id)
);
create index idx_operation_companies_company_log on operation_companies (company_id, operation_log_id);

-- 작업이 대상으로 한 Buptle Cloud 데이터 (외래키 없이 종류와 외부 ID 로 식별)
create table operation_targets (
    id                 bigint generated by default as identity primary key,
    operation_log_id   bigint      not null references operation_logs (id),
    target_type        varchar(30) not null,
    external_target_id varchar(255),
    target_data        jsonb,
    before_data        jsonb,
    after_data         jsonb,
    created_at         timestamptz not null,
    constraint ck_operation_targets_type check (target_type in
        ('COMPANY', 'CONTRACT', 'COUNSEL', 'LITIGATION', 'USER', 'CONFIG', 'SESSION', 'ERROR_REPORT'))
);
create index idx_operation_targets_log on operation_targets (operation_log_id);
create index idx_operation_targets_type_external on operation_targets (target_type, external_target_id);

-- 배치 실행 결과
create table batch_runs (
    id               bigint generated by default as identity primary key,
    batch_type       varchar(30) not null,
    service_platform varchar(30) not null,
    status           varchar(30) not null,
    started_at       timestamptz not null,
    finished_at      timestamptz,
    scanned_count    integer     not null default 0,
    mismatch_count   integer     not null default 0,
    failure_message  text,
    constraint ck_batch_runs_type check (batch_type in ('CONFIG_SYNC')),
    constraint ck_batch_runs_platform check (service_platform in ('BUPTLE_BIZ', 'BUPTLE_NOVA')),
    constraint ck_batch_runs_status check (status in ('RUNNING', 'SUCCEEDED', 'FAILED'))
);
create index idx_batch_runs_type_started on batch_runs (batch_type, started_at);
create index idx_batch_runs_status_started on batch_runs (status, started_at);

-- 알림
create table notices (
    id           bigint generated by default as identity primary key,
    batch_run_id bigint       not null references batch_runs (id),
    notice_type  varchar(30)  not null,
    title        varchar(255) not null,
    content      text         not null,
    created_at   timestamptz  not null,
    resolved_at  timestamptz,
    constraint ck_notices_type check (notice_type in ('MISSING_CONFIG'))
);
create index idx_notices_type_resolved on notices (notice_type, resolved_at);
create index idx_notices_batch_run on notices (batch_run_id);

-- 알림 항목 (미등록 컨피그 1건)
create table notice_items (
    id                   bigint generated by default as identity primary key,
    notice_id            bigint       not null references notices (id),
    missing_config_name  varchar(255) not null,
    detected_data        jsonb,
    registered_config_id bigint references configs (id),
    resolved_at          timestamptz,
    constraint uk_notice_items_notice_name unique (notice_id, missing_config_name)
);
create index idx_notice_items_registered_config on notice_items (registered_config_id);
